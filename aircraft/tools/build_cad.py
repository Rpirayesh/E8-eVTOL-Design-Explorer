"""Parametric concept assembly in millimetres. CAD envelopes, not manufacturing drawings.
Rebuild with CadQuery 2.7.0. The selected design is generated by analyze.py.
"""
from pathlib import Path
import json, math, struct
import cadquery as cq

ROOT=Path(__file__).resolve().parents[1]
COLORS={'airframe':(.77,.82,.85),'canopy':(.23,.58,.71),'structure':(.18,.23,.29),
        'aero':(.89,.93,.92),'rotor':(.18,.23,.29),'motor':(.87,.40,.19),
        'battery':(.20,.62,.52),'systems':(.95,.68,.24),'cabin':(.29,.37,.43),'gear':(.13,.17,.20)}

def box(dx,dy,dz,x=0,y=0,z=0):
    return cq.Workplane('XY').box(dx,dy,dz).val().translate((x,y,z))

def tube(a,b,d,t):
    a=cq.Vector(*a);b=cq.Vector(*b);v=b-a
    return cq.Solid.makeCylinder(d/2,v.Length,a,v.normalized()).cut(cq.Solid.makeCylinder(d/2-t,v.Length,a,v.normalized()))

def cyl(a,b,r):
    a=cq.Vector(*a);b=cq.Vector(*b);v=b-a
    return cq.Solid.makeCylinder(r,v.Length,a,v.normalized())

def airfoil_wire(chord,y,z,xcenter=0,thickness=.22):
    # Closed NACA 00xx geometric envelope; not an aerodynamic selection.
    xs=[(1-math.cos(math.pi*i/36))/2 for i in range(37)]
    def yt(x): return 5*thickness*chord*(.2969*math.sqrt(x)-.126*x-.3516*x*x+.2843*x**3-.1036*x**4)
    pts=[cq.Vector((x-.5)*chord+xcenter,y,z+yt(x)) for x in reversed(xs)]
    pts += [cq.Vector((x-.5)*chord+xcenter,y,z-yt(x)) for x in xs[1:-1]]
    return cq.Wire.makePolygon(pts,close=True)

def loft_sections(sections,inner=False):
    wires=[]
    for x,wy,h,z in sections:
        if inner: wy=max(15,wy-15);h=max(15,h-15)
        wires.append(cq.Workplane('YZ',origin=(x,0,z)).ellipse(wy,h).val())
    return cq.Solid.makeLoft(wires,ruled=False)

def write_stl(path,shapes):
    triangles=[]
    for s in shapes:
        vs,ts=s.tessellate(12,.25)
        triangles.extend([(vs[a],vs[b],vs[c]) for a,b,c in ts])
    with path.open('wb') as f:
        f.write(b'E8 CONCEPT - mm - NO FABRICATION RELEASE'.ljust(80,b' '));f.write(struct.pack('<I',len(triangles)))
        for a,b,c in triangles:
            n=(b-a).cross(c-a)
            if n.Length: n=n.normalized()
            f.write(struct.pack('<12fH',n.x,n.y,n.z,a.x,a.y,a.z,b.x,b.y,b.z,c.x,c.y,c.z,0))

def main():
    p=json.loads((ROOT/'selected_design.json').read_text());out=ROOT/'cad';out.mkdir(exist_ok=True)
    parts=[]
    def add(name,shape,category,**meta):
        if not shape.isValid() or not shape.Solids(): raise RuntimeError('Invalid solid: '+name)
        parts.append(dict(name=name,shape=shape,category=category,color=COLORS[category],**meta))
    sections=[(-2400,80,120,250),(-2050,600,560,260),(-1200,850,850,250),
              (700,850,780,250),(1800,500,440,200),(2400,65,100,150)]
    outer=loft_sections(sections);inside=loft_sections(sections,True)
    shell=outer.cut(inside)
    # Bay/case clearance envelopes only; containment, covers and attachment engineering are open.
    for bx in [-150,1250]:
        for by in [-430,430]:
            shell=shell.cut(box(910,610,290,bx,by,-400))
    window=box(2600,2200,1300,-300,0,1400)
    add('Fuselage_shell_envelope_15mm_not_laminate',shell.cut(window),'airframe')
    add('Canopy_envelope',shell.intersect(window),'canopy')
    add('Cabin_floor',box(3500,1600,45,-50,0,-180),'structure')
    for x in [-1500,-700,200,1000,1700]:
        frame=box(40,1500,1150,x,0,230).cut(box(80,1370,1010,x,0,250))
        add(f'Cabin_bulkhead_{x}',frame,'structure')
    for y in [-700,700]:
        add(f'Cabin_longeron_{y}',tube((-1700,y,-130),(1700,y,-130),65,3),'structure')
    # Rectangular main wing and distinct trailing control surfaces.
    span=p['wing_span_m']*1000;chord=p['wing_area_m2']/p['wing_span_m']*1000
    for sign,side in [(-1,'L'),(1,'R')]:
        wing=cq.Solid.makeLoft([airfoil_wire(chord,0,1600),airfoil_wire(chord,sign*span/2,1600)],ruled=True)
        trailing=box(chord*.25+10,span,1500,chord*.375,sign*span/4,1600)
        add('Wing_envelope_'+side,wing.cut(trailing),'aero',wing_only=True)
        add('Aileron_envelope_'+side,wing.intersect(trailing),'aero',wing_only=True)
    spar=box(120,span,260,-.2*chord,0,1600).cut(box(112,span+2,252,-.2*chord,0,1600))
    add('Main_spar_homogeneous_box_assumption',spar,'structure',wing_only=True)
    whole_wing=cq.Solid.makeLoft([airfoil_wire(chord,-span/2,1600),airfoil_wire(chord,span/2,1600)],ruled=True)
    for y in [-span/2+200,-span/3,-span/6,span/6,span/3,span/2-200]:
        add(f'Wing_rib_envelope_{int(y)}',box(chord*.72,10,150,0,y,1600).intersect(whole_wing),'structure',wing_only=True)
    for y in [-1000,1000]:
        add(f'High_wing_pylon_{y}',box(150,100,700,-.2*chord,y,1250),'structure',wing_only=True)
        add(f'High_wing_support_rail_{y}',tube((-850,y,1000),(850,y,1000),65,3),'structure',wing_only=True)
    # Tail system carried in the aerodynamic-system mass allowance.
    add('Tail_boom',tube((1900,0,150),(3500,0,450),130,4),'structure',wing_only=True)
    tail=cq.Solid.makeLoft([airfoil_wire(1000,-1500,470,3250,.12),airfoil_wire(1000,1500,470,3250,.12)],ruled=True)
    add('Horizontal_tail_envelope',tail,'aero',wing_only=True)
    fin=cq.Workplane('XZ').polyline([(2800,450),(3700,450),(3450,1550),(3050,1550)]).close().extrude(45,both=True).val()
    add('Vertical_tail_envelope',fin,'aero',wing_only=True)
    for sign in [-1,1]:
        y=sign*p['rotor_y_m']*1000
        add(f'Longitudinal_boom_{sign}',tube((-4450,y,1000),(4450,y,1000),150,4),'structure')
        for x in [-850,850]:
            add(f'Outrigger_{sign}_{x}',tube((x,sign*750,1000),(x,y,1000),150,4),'structure')
            add(f'Diagonal_brace_{sign}_{x}',tube((x,sign*720,0),(x,y,1000),65,3),'structure')
    # Four battery-module envelopes. Concept architecture: each 160s4p for selected 16p total.
    for x in [-150,1250]:
        for y in [-430,430]:
            name=f'Battery_module_{x}_{y}'
            add(name,box(900,600,280,x,y,-400),'battery')
            add(name+'_tray',box(970,650,20,x,y,-550),'structure')
    for y in [-400,400]:
        add(f'Seat_cushion_{y}',box(620,500,100,-600,y,80),'cabin')
        add(f'Seat_back_{y}',box(100,500,700,-240,y,450),'cabin')
        add(f'Control_stick_{y}',cyl((-950,y,0),(-950,y,430),17),'cabin')
    add('Instrument_panel_envelope',box(150,1350,320,-1280,0,600),'systems')
    add('Avionics_envelope',box(240,280,100,-1300,0,380),'systems')
    add('Power_distribution_envelope',box(400,300,180,650,0,-50),'systems')
    for y in [-700,700]:
        add(f'Cooling_radiator_envelope_{y}',box(550,80,250,1300,y,150),'systems')
    # Gear: wheels and struts; no braking or crash-load substantiation.
    for x,y in [(500,-1150),(500,1150),(-1850,0)]:
        radius=230 if x>0 else 180
        add(f'Wheel_{x}_{y}',cyl((x,y-65,-1020),(x,y+65,-1020),radius),'gear')
        add(f'Gear_strut_{x}_{y}',tube((x,y,-950),(x,y*.65,-130),65,4),'gear')
    # Tilt pivot lies .4m behind each propeller along the rotor axis.
    # This prevents the cruise rotor plane from intersecting its support post.
    r=p['rotor_diameter_m']*500;hubz=p['rotor_hub_z_m']*1000;pivotz=hubz-400
    centres=[]
    for i,(xm,ym) in enumerate([(x,y) for x in p['rotor_rows_x_m'] for y in [-p['rotor_y_m'],p['rotor_y_m']]]):
        x=xm*1000;y=ym*1000;pivot=[x,y,pivotz];centres.append([xm,ym,hubz/1000])
        add(f'R{i+1}_standoff',tube((x,y,1000),(x,y,pivotz-140),100,5),'structure')
        add(f'R{i+1}_fork_crosshead',box(140,400,70,x,y,pivotz-160),'structure')
        add(f'R{i+1}_tilt_axle',cyl((x,y-200,pivotz),(x,y+200,pivotz),35),'structure')
        add(f'R{i+1}_tilt_actuator_envelope',box(250,160,200,x,y+260,pivotz-40),'systems')
        for dy in [-160,160]:
            add(f'R{i+1}_fork_{dy}',box(130,40,240,x,y+dy,pivotz-100),'structure')
        add(f'R{i+1}_motor_REB50_envelope',cyl((x,y,hubz-260),(x,y,hubz-60),133.4),'motor',rotor=i,pivot_mm=pivot)
        add(f'R{i+1}_rotating_yoke_envelope',cyl((x,y,pivotz-20),(x,y,hubz-240),50),'structure',rotor=i,pivot_mm=pivot)
        add(f'R{i+1}_hub',cyl((x,y,hubz-65),(x,y,hubz+35),72),'motor',rotor=i,pivot_mm=pivot)
        add(f'R{i+1}_inverter_envelope',box(310,220,90,x+250,y,1090),'systems')
        add(f'R{i+1}_cable_route_envelope',cyl((x,y+90,1120),(x,y+90,pivotz-150),12),'systems')
        # Planform silhouettes only: pitch/twist/airfoil and root fittings are intentionally unspecified.
        for blade in range(2):
            pts=[(60,-45),(r*.42,-100),(r*.83,-75),(r,0),(r*.83,45),(r*.42,65),(60,45)]
            shape=cq.Workplane('XY').polyline(pts).close().extrude(10,both=True).val()
            angle=blade*180+(i%2)*35
            shape=shape.rotate((0,0,0),(0,0,1),angle).translate((x,y,hubz))
            add(f'R{i+1}_blade_{blade+1}_VISUAL_ONLY',shape,'rotor',rotor=i,pivot_mm=pivot)
    # Named STEP assembly, STL for GitHub preview, and tessellation for offline viewer/rendering.
    def assembly(winged=True,tilt=0):
        a=cq.Assembly(name='E8_concept_'+('winged' if winged else 'wingless'))
        shapes=[]
        for part in parts:
            if part.get('wing_only') and not winged: continue
            shape=part['shape']
            if 'rotor' in part and tilt:
                pv=part['pivot_mm'];shape=shape.rotate(pv,(pv[0],pv[1]+1,pv[2]),-tilt)
            a.add(shape,name=part['name'],color=cq.Color(*part['color']));shapes.append(shape)
        return a,shapes
    for name,winged,tilt in [('E8_Winged_Hover',True,0),('E8_Winged_Cruise',True,90),('E8_Wingless_Hover',False,0)]:
        a,shapes=assembly(winged,tilt);a.export(str(out/(name+'.step')))
        if tilt==0: write_stl(out/(name+'.stl'),shapes)
    mesh=[];manifest=[]
    for part in parts:
        vs,ts=part['shape'].tessellate(12,.25)
        meta={k:v for k,v in part.items() if k!='shape'}
        mesh.append(dict(**meta,vertices=[[round(v.x/1000,5),round(v.y/1000,5),round(v.z/1000,5)] for v in vs],triangles=ts))
        bounds=part['shape'].BoundingBox()
        manifest.append(dict(**meta,valid=part['shape'].isValid(),solids=len(part['shape'].Solids()),
            geometric_volume_mm3=part['shape'].Volume(),bbox_mm=[bounds.xmin,bounds.ymin,bounds.zmin,bounds.xmax,bounds.ymax,bounds.zmax]))
    (ROOT/'viewer'/'mesh.json').write_text(json.dumps(mesh,separators=(',',':')))
    (out/'assembly_manifest.json').write_text(json.dumps(dict(units='mm',components=manifest,
         note='Geometric volumes are not a mass model. External aero solids overlap internal structure intentionally.'),indent=2)+'\n')
    metrics=dict(component_count=len(parts),valid_components=sum(x['valid'] for x in manifest),
        hover_neighbour_gap_m=min(abs(b-a) for a,b in zip(p['rotor_rows_x_m'],p['rotor_rows_x_m'][1:]))-p['rotor_diameter_m'],
        asynchronous_tilt_conservative_gap_m=min(abs(b-a) for a,b in zip(p['rotor_rows_x_m'],p['rotor_rows_x_m'][1:]))-.4-p['rotor_diameter_m'],
        cruise_disk_bottom_m=p['rotor_hub_z_m']-.4-p['rotor_diameter_m']/2,
        boom_top_m=1.075,rotor_centres_m=centres,wing_span_m=p['wing_span_m'],wing_chord_m=chord/1000)
    (out/'geometry_checks.json').write_text(json.dumps(metrics,indent=2)+'\n')
    # OpenSCAD independently opens the exported hover mesh; no vendor add-ons needed.
    (out/'E8_Assembly.scad').write_text('// Concept visualization only; units mm. Set winged=false for wingless.\nwinged=true;\nimport(winged ? "E8_Winged_Hover.stl" : "E8_Wingless_Hover.stl", convexity=20);\n')
    print(json.dumps(metrics,indent=2))

if __name__=='__main__':main()
